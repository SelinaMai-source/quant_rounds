def require_hypotheses() -> list[dict[str, Any]]:
    ids = [c["factor_id"] for c in HYPOTHESES]
    if tuple(ids) != NEW_FACTOR_IDS:
        raise RuntimeError(f"hypothesis ids mismatch: {ids}")
    return list(HYPOTHESES)


def run_hypotheses(*, resume: bool = True, **_: Any) -> dict[str, Any]:
    if resume and HYP_JSON.is_file() and HYP_YAML.is_file() and MD["03"].is_file():
        from .common import load_json

        existing = load_json(HYP_JSON)
        if existing.get("status") == "FROZEN":
            return existing
    cards = require_hypotheses()
    HYP_YAML.parent.mkdir(parents=True, exist_ok=True)
    HYP_YAML.write_text(yaml.safe_dump({"round": "21.2", "n": len(cards), "hypotheses": cards}, allow_unicode=True, sort_keys=False), encoding="utf-8")
    manifest = {
        "round": "21.2",
        "n_formulas": 32,
        "families": list("GHIJKLMN"),
        "rolling_windows": [60, 120, 252],
        "cluster_spearman": 0.85,
        "interaction_cap": 120,
        "subsample": 1.0,
        "colsample": 1.0,
        "fusion": "0.90 ten + 0.10 five",
        "current": "baseline_v5=R16_O01",
        "auto_promote": False,
        "frozen_before_nav": True,
    }
    MANIFEST.write_text(yaml.safe_dump(manifest, allow_unicode=True, sort_keys=True), encoding="utf-8")
    payload = {
        "status": "FROZEN",
        "n": len(cards),
        "ids": [c["factor_id"] for c in cards],
        "sha256": sha256_json(cards),
        "manifest_sha256": sha256_json(manifest),
        "frozen_before_nav": True,
    }
    dump_json(HYP_JSON, payload)
    lines = ["# Round21.2 · 03 新因子假设卡", "", f"冻结 N=`{len(cards)}` sha256=`{payload['sha256']}`。看 NAV 之前。", ""]
    for c in cards:
        lines.append(f"- `{c['factor_id']}` [{c['family']}] {c['short']}：`{c['formula']}` PIT={c['pit']}")
    write_md(MD["03"], "\n".join(lines))
    return payload
